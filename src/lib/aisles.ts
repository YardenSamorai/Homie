const known = new Map<string, Aisle>();
for (const aisle of Object.keys(words) as Exclude<Aisle, "other">[]) {
  for (const word of words[aisle]) if (!known.has(looseKey(word))) known.set(looseKey(word), aisle);
}

/**
 * The aisle for a product this app already knows, without asking anyone: the whole name first
 * ("עגבניות מרוסקות" is a can), then its first word ("חלב שלי" is still milk).
 */
export function knownAisle(name: string): Aisle | null {
  const key = looseKey(name);
  if (!key) return null;
  const whole = known.get(key);
  if (whole) return whole;
  const first = key.split(" ")[0];
  return first !== key ? known.get(first) ?? null : null;
}
