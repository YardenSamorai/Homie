export const isAisle = (value: unknown): value is Aisle =>
  typeof value === "string" && (AISLES as readonly string[]).includes(value);

const finals: Record<string, string> = { ך: "כ", ם: "מ", ן: "נ", ף: "פ", ץ: "צ" };

/** One word with spelling, final letters and plural endings aside: עגבניה and עגבניות, קוטג' and קוטג. */
function stem(word: string) {
  let w = word.replace(/[ךםןףץ]/g, (letter) => finals[letter]);
  if (/[\u05d0-\u05ea]/.test(w)) {
    if (w.length > 3 && /(ימ|ות)$/.test(w)) w = w.slice(0, -2);
    if (w.length > 2 && w.endsWith("ה")) w = w.slice(0, -1);
    return w;
  }
  if (w.length > 4 && w.endsWith("es")) return w.slice(0, -2);
  if (w.length > 3 && w.endsWith("s")) return w.slice(0, -1);
  return w;
}

/** Two names that are probably the same product. Looser than the list's own duplicate check, so only ever a suggestion. */
export function looseKey(name: string) {
  return name
    .trim()
    .toLowerCase()
    .replace(/[\u0591-\u05C7]/g, "")
    .replace(/['"׳״`.,()\-]/g, "")
    .split(/\s+/)
    .filter(Boolean)
    .map(stem)
    .join(" ");
}

